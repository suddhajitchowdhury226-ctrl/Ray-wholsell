// ── Schema (strict:false so we can add the new field) ─────────────────────────
const productSchema = new mongoose.Schema({
  rhlId: { type: Number, required: true, unique: true },
  name:  { type: String },
  rhlProductTitle: { type: String, default: null },
}, { strict: false, timestamps: true });

const Product = mongoose.model('Product', productSchema);

// ── Main ──────────────────────────────────────────────────────────────────────
async function main() {
  console.log('━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━');
  console.log('  Product Title Update — v4');
  console.log('  Sets rhlProductTitle on all 408 products');
  console.log('━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n');

  await mongoose.connect(MONGO_URI);
  console.log('✅  Connected to MongoDB\n');

  const stats = { updated: 0, notFound: [], errors: [] };

  for (const [rhlIdStr, title] of Object.entries(TITLE_MAP)) {
    const rhlId = parseInt(rhlIdStr, 10);
    try {
      const result = await Product.findOneAndUpdate(
        { rhlId },
        { $set: { rhlProductTitle: title } },
        { new: false }
      );
      if (!result) {
        stats.notFound.push(rhlId);
      } else {
        stats.updated++;
      }
    } catch (err) {
      stats.errors.push({ rhlId, error: err.message });
    }
  }

  console.log('━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━');
  console.log('  Results');
  console.log('━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━');
  console.log(`  Updated        : ${stats.updated}`);
  console.log(`  Not found in DB: ${stats.notFound.length}`);
  console.log(`  Errors         : ${stats.errors.length}`);

  if (stats.notFound.length > 0) {
    console.log(`\n⚠️   rhlIds not found: ${stats.notFound.join(', ')}`);
  }
  if (stats.errors.length > 0) {
    stats.errors.forEach(e => console.error(`  ❌  rhlId ${e.rhlId}: ${e.error}`));
  }

  // Spot-check: show first 5 updated records
  console.log('\n📋  Spot-check (first 5):');
  const sample = await Product.find({ rhlId: { $in: [200, 201, 202, 203, 204] } })
    .select('rhlId name rhlProductTitle')
    .lean();
  sample.forEach(p =>
    console.log(`  RHL#${p.rhlId}  |  name: "${p.name}"  |  rhlProductTitle: "${p.rhlProductTitle}"`)
  );

  if (stats.errors.length === 0 && stats.notFound.length === 0) {
    console.log('\n✅  All products updated successfully');
  }

  await mongoose.disconnect();
}

main().catch(err => { console.error('Fatal:', err); process.exit(1); });
