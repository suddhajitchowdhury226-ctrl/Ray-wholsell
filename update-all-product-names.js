async function connectDB() {
  try {
    await mongoose.connect(process.env.DATABASE_URL);
    console.log('✅ Connected to MongoDB');
  } catch (error) {
    console.error('❌ DB Connection Error:', error.message);
    process.exit(1);
  }
}

async function updateAllProductNames() {
  console.log('🚀 Starting product name update with exact master list names...');
  console.log('==================================================\n');

  try {
    const totalProducts = await Product.countDocuments();
    console.log(`📊 Total products in database: ${totalProducts}`);
    console.log(`📋 Products in master list: ${CORRECT_PRODUCT_NAMES.length}\n`);

    let updatedCount = 0;
    let errorCount = 0;

    // Get all products and update them in order
    const products = await Product.find().sort({ _id: 1 });

    for (let i = 0; i < products.length && i < CORRECT_PRODUCT_NAMES.length; i++) {
      try {
        const product = products[i];
        const correctName = CORRECT_PRODUCT_NAMES[i];

        // Update product with correct name
        await Product.findByIdAndUpdate(
          product._id,
          {
            name: correctName,
            originalProductName: correctName
          },
          { new: true }
        );

        updatedCount++;

        // Show progress every 50 products
        if ((updatedCount) % 50 === 0) {
          console.log(`  ✅ Updated ${updatedCount}/${Math.min(products.length, CORRECT_PRODUCT_NAMES.length)} products...`);
        }

        // Show first 5 updates
        if (i < 5) {
          console.log(`\n  ✅ Product ${i + 1}:`);
          console.log(`     Old name: "${product.name}"`);
          console.log(`     New name: "${correctName}"`);
        }
      } catch (error) {
        errorCount++;
        console.error(`  ❌ Error updating product ${i + 1}:`, error.message.substring(0, 80));
      }
    }

    console.log('\n\n📊 Update Summary:');
    console.log(`  ✅ Successfully updated: ${updatedCount} products`);
    console.log(`  ❌ Errors: ${errorCount}`);
    console.log(`  📋 Products in database: ${totalProducts}`);
    console.log(`  📋 Products in master list: ${CORRECT_PRODUCT_NAMES.length}`);

    if (updatedCount === CORRECT_PRODUCT_NAMES.length) {
      console.log('\n✨ All products updated with correct names!');
    }

  } catch (error) {
    console.error('❌ Process error:', error.message);
  }
}

async function main() {
  await connectDB();
  await updateAllProductNames();

  console.log('\n==================================================');
  console.log('✅ Product name update completed!');
  console.log('Product pages will now display correct names!');
  console.log('==================================================\n');

  process.exit(0);
}

main().catch(error => {
  console.error('Fatal error:', error);
  process.exit(1);
});
